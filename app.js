import { injectStyles } from "./style.js";
import { renderKpis } from "./js/dashboard.js";
import { renderCharts } from "./js/charts.js";
import { renderTable,populateFilters,exportCsv } from "./js/table.js";
import { setupForm } from "./js/form.js";
import { loadRecords,saveRecords,resetRecords } from "./js/storage.js";
injectStyles();
let records=loadRecords();
const rerender=()=>{renderKpis(records);renderCharts(records);renderTable(records)};
const setRecords=value=>{records=value;saveRecords(records)};
populateFilters();
setupForm({getRecords:()=>records,setRecords,rerender});
document.querySelector("#searchInput").addEventListener("input",()=>renderTable(records));
document.querySelector("#equipmentFilter").addEventListener("change",()=>renderTable(records));
document.querySelector("#typeFilter").addEventListener("change",()=>renderTable(records));
document.querySelector("#printBtn").addEventListener("click",()=>window.print());
document.querySelector("#exportBtn").addEventListener("click",()=>exportCsv(records));
document.querySelector("#themeBtn").addEventListener("click",()=>{const root=document.documentElement;root.dataset.theme=root.dataset.theme==="dark"?"light":"dark";});
const resetButton=document.querySelector("#resetBtn");
if(resetButton)resetButton.addEventListener("click",()=>{if(confirm("Reset semua catatan ke data awal laporan?")){records=resetRecords();rerender()}});
document.querySelector("#dataNotice").textContent="Sumber data awal: Laporan KP, Tabel 2.4 (peralatan), Tabel 3.9 (riwayat gangguan 10 Jan–29 Sep 2026), dan Tabel 3.10 (jadwal PM usulan). Data awal berisi 17 catatan. Pelaksana dan pemeriksaan berikutnya belum tercantum pada data awal.";
rerender();
